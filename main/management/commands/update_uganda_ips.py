from ipaddress import ip_address, ip_network
from urllib.request import urlopen

from django.core.management.base import BaseCommand

from main.currency import UGANDA_IPS

SOURCE = 'https://ftp.afrinic.net/pub/stats/afrinic/delegated-afrinic-extended-latest'


class Command(BaseCommand):
    help = "Refresh Uganda's IP ranges (used to show UGX prices by default) from the AFRINIC registry."

    def handle(self, *args, **options):
        with urlopen(SOURCE, timeout=60) as resp:
            text = resp.read().decode('utf-8', 'replace')

        ranges = []
        for line in text.splitlines():
            parts = line.split('|')
            if len(parts) < 7 or parts[1] != 'UG' or parts[6] not in ('allocated', 'assigned'):
                continue
            if parts[2] == 'ipv4':
                first = ip_address(parts[3])
                ranges.append((first, first + int(parts[4]) - 1))
            elif parts[2] == 'ipv6':
                net = ip_network(f'{parts[3]}/{parts[4]}')
                ranges.append((net.network_address, net.broadcast_address))

        # Merge neighbouring blocks to keep the file short.
        merged = []
        for first, last in sorted(ranges, key=lambda r: (r[0].version, r[0])):
            prev = merged[-1] if merged else None
            if prev and prev[0].version == first.version and int(first) <= int(prev[1]) + 1:
                merged[-1] = (prev[0], max(prev[1], last))
            else:
                merged.append((first, last))

        UGANDA_IPS.parent.mkdir(exist_ok=True)
        UGANDA_IPS.write_text(
            f'# Uganda IP ranges (first last), generated by `manage.py update_uganda_ips` from\n# {SOURCE}\n'
            + ''.join(f'{a} {b}\n' for a, b in merged)
        )
        self.stdout.write(self.style.SUCCESS(f'Wrote {len(merged)} ranges to {UGANDA_IPS}'))
